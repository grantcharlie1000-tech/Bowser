// Regenerates vendor/noble-ed25519/noble-ed25519.js, the classic-script (importScripts-able) form of
// @noble/ed25519 3.2.0 (MIT), from the npm package's index.js. The service worker is a classic script
// (build/validate.mjs forbids type: module) and ES module syntax cannot be importScripts()-ed, so the only
// changes are: the `export {...}` line becomes an assignment to self.nobleEd25519, the code is wrapped in an
// IIFE, and non-ASCII characters (comments only) are written as \uXXXX escapes.
//
//   npm pack @noble/ed25519@3.2.0 ; tar xzf noble-ed25519-3.2.0.tgz
//   node feed/tools/vendor-noble.mjs package/index.js
//
// Refuses any upstream file whose SHA-256 is not the reviewed one below.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const UPSTREAM_SHA256 = "a4f631d1876b5d9e43a86cd71194ca27b5e1451edf4ba4db9a418f40a475569a"; // index.js of @noble/ed25519@3.2.0
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

export function wrap(upstream) {
  const m = /\nexport \{([^}]*)\};?\s*$/.exec(upstream);
  if (!m) throw new Error("upstream index.js has no trailing export list");
  const names = m[1].split(",").map((s) => s.trim()).filter(Boolean);
  const body = upstream.slice(0, m.index);
  let out =
    "/* @noble/ed25519 3.2.0 (c) Paul Miller, MIT License: https://github.com/paulmillr/noble-ed25519\n" +
    "   Classic-script wrapper generated by feed/tools/vendor-noble.mjs (see vendor/README.md); the code below is upstream's. */\n" +
    '(function (root) {\n"use strict";\n' + body +
    "\nroot.nobleEd25519 = { " + names.join(", ") + " };\n" +
    '})(typeof self !== "undefined" ? self : globalThis);\n';
  return out.replace(/[^\x00-\x7f]/g, (ch) => "\\u" + ch.charCodeAt(0).toString(16).padStart(4, "0"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === (await import("node:path")).resolve(process.argv[1])) {
  const src = readFileSync(process.argv[2] || "package/index.js");
  const sha = createHash("sha256").update(src).digest("hex");
  if (sha !== UPSTREAM_SHA256) throw new Error(`upstream index.js SHA-256 ${sha} is not the reviewed ${UPSTREAM_SHA256}`);
  const out = wrap(src.toString("utf8"));
  const dest = join(ROOT, "vendor", "noble-ed25519", "noble-ed25519.js");
  writeFileSync(dest, out);
  console.log(`wrote ${dest} sha256=${createHash("sha256").update(out).digest("hex")}`);
}
