// Build script for Spoiler Firewall. Node 18+, no dependencies.
//
// The engine is a set of classic-script fragments in engine/. Each fragment assigns one member of
// the closure-scoped `SFW` object. This script concatenates them in ENGINE_ORDER inside a single
// closure and emits three artefacts from the same engine text:
//
//   dist/node/engine.cjs                 module.exports = SFW (tests run the shipped engine)
//   dist/chrome/...                      unpacked MV3 extension (content.js = engine + chrome host)
//   dist/bowser/spoiler-firewall.js      one IIFE: engine + Bowser host, config placeholder
//
// Usage: node build/build.mjs [--check]
//   --check  rebuild in memory and fail if any committed dist file differs (stale bundle guard).

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, copyFileSync, existsSync, rmSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

export const ENGINE_ORDER = [
  "normalize.js",
  "lexicon.js",
  "classify.js",
  "policy.js",
  "adapters.js",
  "styles.js",
  "shield.js",
  "hooks.js",
  "runtime.js",
];

const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
export const VERSION = pkg.version;

function read(rel) {
  return readFileSync(join(ROOT, rel), "utf8").replace(/\r\n/g, "\n");
}

export function engineSource() {
  const parts = ENGINE_ORDER.map((file) => `// ---- engine/${file} ----\n${read(join("engine", file))}`);
  return withSnapshot(parts.join("\n"));
}

// The compiled lexicon, computed here once instead of in every document (engine/lexicon.js, "build-time snapshot"):
// the engine is evaluated in this process, compile() runs, and its encoded result is embedded right after lexicon.js.
// The page revives it only if its own normaliser reproduces the snapshot's sample keys; otherwise it compiles as before.
const SNAPSHOT_AFTER = "// ---- engine/lexicon.js ----\n";
function withSnapshot(engine) {
  const SFW = new Function(`return ${closure(engine, "return SFW;")};`)();
  const text = SFW.lexicon.encodeSnapshot();
  const at = engine.indexOf(SNAPSHOT_AFTER);
  const next = engine.indexOf("\n// ---- engine/", at + SNAPSHOT_AFTER.length);
  if (at < 0 || next < 0) throw new Error("engine fragment markers not found for the lexicon snapshot");
  const fragment = `\n// ---- generated: lexicon snapshot (build/build.mjs) ----\nSFW.lexicon.setSnapshot(${JSON.stringify(text)});`;
  return engine.slice(0, next) + fragment + engine.slice(next);
}

// Every emitted script is pure ASCII: each non-ASCII UTF-16 code unit becomes a \uXXXX escape.
// Chrome rejects content scripts containing noncharacters (e.g. raw U+FFFF), and Bowser passes the
// bundle through a wide-string API. Escapes are semantics-preserving in string literals, template
// literals, regex literals (with or without the u flag) and comments. The one unsafe spelling — a
// backslash directly before a raw non-ASCII character (an identity escape) — is refused.
export function asciiEscape(text, label) {
  if (/\\[^\x00-\x7f]/.test(text)) {
    throw new Error(`${label}: backslash before a raw non-ASCII character; write it as a \\u escape`);
  }
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    out += code < 0x80 ? text[i] : "\\u" + code.toString(16).padStart(4, "0");
  }
  return out;
}

function closure(body, tail) {
  return (
    `(function () {\n"use strict";\nconst SFW = { version: ${JSON.stringify(VERSION)} };\n` +
    `${body}\n${tail}\n})()`
  );
}

const BANNER = `/* Spoiler Firewall for GTA VI ${VERSION} — unofficial, not affiliated with Rockstar Games. Generated by build/build.mjs; do not edit. */\n`;

function outputs() {
  const engine = engineSource();
  const files = new Map();

  files.set("dist/node/engine.cjs", BANNER + "module.exports = " + closure(engine, "return SFW;") + ";\n");

  // Chrome: isolated-world content script = engine + chrome host, one file.
  const chromeHost = read("hosts/chrome/content.js");
  files.set("dist/chrome/content.js", BANNER + closure(engine, `// ---- hosts/chrome/content.js ----\n${chromeHost}`) + ";\n");

  // Static Chrome files are copied as-is (manifest version is stamped from package.json).
  const chromeDir = join(ROOT, "hosts", "chrome");
  for (const rel of walk(chromeDir)) {
    if (rel === "content.js") continue;
    const src = join(chromeDir, rel);
    const dest = `dist/chrome/${rel.split("\\").join("/")}`;
    if (rel === "manifest.json") {
      const manifest = JSON.parse(readFileSync(src, "utf8"));
      manifest.version = VERSION;
      files.set(dest, JSON.stringify(manifest, null, 2) + "\n");
    } else {
      files.set(dest, { copyFrom: src });
    }
  }
  // MAIN-world hooks (attachShadow marking, media play guard) for the Chrome host: only hooks.js.
  files.set(
    "dist/chrome/content-main.js",
    BANNER + closure(`// ---- engine/hooks.js ----\n${read("engine/hooks.js")}`, "SFW.hooks.install(globalThis);") + ";\n",
  );
  const vendorDir = join(ROOT, "vendor");
  if (existsSync(vendorDir)) {
    for (const rel of walk(vendorDir)) {
      files.set(`dist/chrome/vendor/${rel.split("\\").join("/")}`, { copyFrom: join(vendorDir, rel) });
    }
  }

  // Bowser: one IIFE. Native code replaces the placeholder with a JSON config object.
  const bowserHost = read("hosts/bowser/bowser-host.js");
  files.set(
    "dist/bowser/spoiler-firewall.js",
    BANNER + closure(engine, `// ---- hosts/bowser/bowser-host.js ----\n${bowserHost}`) + ";\n",
  );
  return files;
}

function walk(dir, base = dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, base));
    else out.push(relative(base, full));
  }
  return out;
}

function sha(buf) {
  return createHash("sha256").update(buf).digest("hex");
}

function main() {
  const files = outputs();
  const stale = [];
  if (!CHECK) {
    for (const d of ["dist/chrome", "dist/node", "dist/bowser"]) rmSync(join(ROOT, d), { recursive: true, force: true });
  }
  for (const [rel, content] of files) {
    const dest = join(ROOT, rel);
    const text = typeof content === "string" && /\.c?js$/.test(rel) ? asciiEscape(content, rel) : content;
    const bytes = typeof text === "string" ? Buffer.from(text, "utf8") : readFileSync(content.copyFrom);
    if (CHECK) {
      // Only the Bowser bundle is committed; it must match the engine sources exactly.
      if (rel !== "dist/bowser/spoiler-firewall.js") continue;
      if (!existsSync(dest) || sha(readFileSync(dest)) !== sha(bytes)) stale.push(rel);
      continue;
    }
    mkdirSync(dirname(dest), { recursive: true });
    if (typeof text === "string") writeFileSync(dest, bytes);
    else copyFileSync(content.copyFrom, dest);
  }
  if (CHECK) {
    if (stale.length) {
      console.error(`Stale build output: ${stale.join(", ")}. Run: node build/build.mjs`);
      process.exit(1);
    }
    console.log("dist/bowser bundle is up to date.");
    return;
  }
  console.log(`Built ${files.size} files (version ${VERSION}).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === (await import("node:path")).resolve(process.argv[1])) main();
