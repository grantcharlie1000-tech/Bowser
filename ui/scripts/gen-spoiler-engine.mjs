// Generates src/spoiler-engine.gen.ts: the Spoiler Firewall's pure detection fragments, so the chrome
// UI masks spoilers with the SAME engine code the page injection runs (one classifier, no copy).
//
// This is a temporary stand-in for a build output of extensions/spoiler-firewall/build/build.mjs
// (an ES module, dist/ui/engine.mjs). It reads engine/{normalize,lexicon,classify,policy}.js in that
// order and wraps them as build.mjs's closure() does (same banner comment per fragment, CRLF
// normalised, ASCII-escaped), so it is the same engine source the shipped bundle is built from (the
// Bowser bundle then strips its comments and indentation; build/minify.mjs changes no token). Nothing
// from the DOM runtime (adapters, styles, shield, hooks, runtime) is included.
//
//   node scripts/gen-spoiler-engine.mjs           write src/spoiler-engine.gen.ts
//   node scripts/gen-spoiler-engine.mjs --check   fail when the committed file is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const sfw = join(here, '..', '..', 'extensions', 'spoiler-firewall');
const out = join(here, '..', 'src', 'spoiler-engine.gen.ts');
const FRAGMENTS = ['normalize.js', 'lexicon.js', 'classify.js', 'policy.js'];

const version = JSON.parse(readFileSync(join(sfw, 'package.json'), 'utf8')).version;
const read = (file) => readFileSync(join(sfw, 'engine', file), 'utf8').replace(/\r\n/g, '\n');
const body = FRAGMENTS.map((file) => `// ---- engine/${file} ----\n${read(file)}`).join('\n');

// Same rule as build.mjs asciiEscape: every non-ASCII UTF-16 unit becomes a \uXXXX escape.
const BACKSLASH = String.fromCharCode(92);
function asciiEscape(text) {
  if (new RegExp(`${BACKSLASH}${BACKSLASH}[^\\x00-\\x7f]`).test(text)) {
    throw new Error('backslash before a raw non-ASCII character; write it as a unicode escape in the engine');
  }
  let result = '';
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    result += code < 0x80 ? text[i] : `${BACKSLASH}u${code.toString(16).padStart(4, '0')}`;
  }
  return result;
}

const text = asciiEscape(
  `// Generated by scripts/gen-spoiler-engine.mjs from extensions/spoiler-firewall/engine; do not edit.\n` +
  `// @ts-nocheck\n"use strict";\nconst SFW = { version: ${JSON.stringify(version)} };\n${body}\nexport default SFW;\n`,
);

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('src/spoiler-engine.gen.ts is stale: run node scripts/gen-spoiler-engine.mjs');
    process.exit(1);
  }
  console.log('spoiler engine is up to date');
} else {
  writeFileSync(out, text);
  console.log(`  src/spoiler-engine.gen.ts  ${(Buffer.byteLength(text) / 1024).toFixed(1)}kb (engine ${version})`);
}
