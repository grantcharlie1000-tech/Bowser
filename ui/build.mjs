// Deterministic per-surface ES modules and genuinely shared chunks, CSS and static HTML.
// The generated Rust allowlist embeds exactly these scripts; runtime never reads the filesystem.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = join(here, 'src');
const distDir = join(here, 'dist');

// Remove stale hashed chunks so the embedded allowlist is exact and reproducible.
rmSync(distDir, { recursive: true, force: true });
mkdirSync(distDir, { recursive: true });
const surfaces = ['toolbar', 'tabs', 'rail', 'panel', 'popup', 'dialog', 'bar', 'hover', 'split', 'downloads'];
await esbuild.build({
  entryPoints: {
    app: join(srcDir, 'main.ts'),
    ...Object.fromEntries(surfaces.map((name) => [name, join(srcDir, 'entries', `${name}.ts`)])),
    ...Object.fromEntries(['settings-page', 'history-page', 'start-page'].map((name) => [name, join(srcDir, `${name}.ts`)])),
  },
  bundle: true,
  splitting: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: 'chrome110',
  legalComments: 'none',
  outdir: distDir,
  entryNames: '[name]',
  chunkNames: 'chunks/[name]-[hash]',
  logLevel: 'info',
});

// Compile-time closed allowlist, not a runtime filesystem or wildcard handler.
function scripts(dir, prefix = '') {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const name = `${prefix}${entry.name}`;
    return entry.isDirectory() ? scripts(join(dir, entry.name), `${name}/`) : name.endsWith('.js') ? [name] : [];
  });
}
const names = scripts(distDir).sort();
writeFileSync(join(distDir, 'scripts.rs'), '// Generated by ui/build.mjs. Do not edit.\nconst SCRIPT_ASSETS: &[(&str, &[u8])] = &[\n'
  + names.map((name) => `    ("${name}", include_bytes!("${name}")),\n`).join('') + '];\n');

const cssEntry = join(srcDir, 'styles', 'app.css');
const css = await postcss([tailwind({ base: srcDir, optimize: { minify: true } })]).process(
  readFileSync(cssEntry, 'utf8'),
  { from: cssEntry, to: join(distDir, 'app.css'), map: false },
);
for (const warning of css.warnings()) console.warn(`app.css: ${warning.toString()}`);
// Normalise line endings so a CRLF checkout of src/ builds the same bytes as an LF one.
writeFileSync(join(distDir, 'app.css'), `${css.css.replace(/\r\n/g, '\n').trimEnd()}\n`);
console.log(`  dist/app.css  ${(Buffer.byteLength(css.css) / 1024).toFixed(1)}kb`);

copyFileSync(join(srcDir, 'index.html'), join(distDir, 'index.html'));
